/** The ceiling IS the list's length, so the two cannot disagree. */
export const BIOME_SKY_CEILING = INTERIORS_FROM_THE_BIOME.length;

const ATMOSPHERIC = new Map<string, boolean>();
const SKY = new Map<string, boolean>();

function walk(dir: string, out: string[] = []): string[] {
  try {
    for (const f of packSrcFiles(dir)) out.push(f);
  } catch {
    // no such tree
  }
  return out;
}

/**
 * ⭐ The classes that declare their own roof — derived, never listed: any
 * source file that overrides `roofDefaults(` (the mixin's own base
 * declaration excluded).
 */
function roofDeclaringClasses(sources: readonly PackSource[]): string[] {
  const files = [...walk(MUD), ...sources.flatMap((s) => walk(s.srcDir))];
  const out: string[] = [];
  for (const file of files) {
    if (file.endsWith("lib/biome/Atmospheric.ts")) continue;
    const src = readFileSync(file, "utf8");
    if (!/\boverride\s+roofDefaults\s*\(|public\s+roofDefaults\s*\(/.test(src)) continue;
    const cp = classPathOfFile(file, sources);
    if (cp) out.push(cp);
  }
  return out;
}

export interface Census {
  counted: string[];
  rows: number;
}

export function census(): Census {
  const sources = packSources();
  const declaring = roofDeclaringClasses(sources);
  const idx = inheritanceIndex();
  const all = templateRows();
  const effective = new Map<string, { class: string; data: Record<string, unknown> }>();
  for (const [path, row] of all) {
    const eff = effectiveDoc(row.file, row.raw, idx);
    if (typeof eff.class !== "string") continue;
    effective.set(path, {
      class: eff.class,
      data: (eff.data as Record<string, unknown>) ?? {},
    });
  }
  const isSky = (biome: string): boolean => {
    const b = effective.get(biome);
    return !!b && composesMixin(b.class, "SkyExposedMixin", sources, SKY);
  };
  const counted: string[] = [];
  let rows = 0;
  for (const [path, row] of effective) {
    if (!composesMixin(row.class, "AtmosphericMixin", sources, ATMOSPHERIC)) continue;
    rows++;
    const biome = row.data._biomePath;
    if (typeof biome === "string" && isSky(biome)) continue;
    if (extendsAny(row.class, declaring, 0, sources)) continue;
    // An off-stage parking room is not a place: it has no volume and no air.
    if (extendsAny(row.class, ["/platform/location/Offstage"], 0, sources)) continue;
    if (row.data.enclosure !== undefined && row.data.roof !== undefined) continue;
    counted.push(path);
  }
  counted.sort();
  return { counted, rows };
}

function report(): void {
  const { counted } = census();
  console.log(`// ${counted.length} interior(s) whose construction comes from the biome`);
  for (const p of counted) console.log(`  "${p}",`);
}

function lint(): void {
  const { counted, rows } = census();
  const listed = new Set(INTERIORS_FROM_THE_BIOME);
  const now = new Set(counted);
  const failures: string[] = [];
  for (const p of counted) {
    if (listed.has(p)) continue;
    failures.push(
      `'${p}' is an interior (its biome is not sky-exposed) that does not ` +
        `say what it is made of. ⭐ Author BOTH \`enclosure:\` (the walls) ` +
        `and \`roof:\` on the row — a material and a thickness, a list of ` +
        `layers, or \`none\`. Never add it to the list: the list only falls.`,
    );
  }
  for (const p of INTERIORS_FROM_THE_BIOME) {
    if (now.has(p)) continue;
    failures.push(
      `'${p}' is listed but no longer takes its construction from its ` +
        `biome — the debt is PAID. Delete its line; the ceiling falls with it.`,
    );
  }
  if (INTERIORS_FROM_THE_BIOME.length > BIOME_SKY_CEILING) {
    failures.push(`the list is longer than its ceiling (${BIOME_SKY_CEILING}).`);
  }
  if (failures.length) {
    console.error(`\n✖ lint:biome-sky — ${failures.length} finding(s):\n`);
    for (const f of failures) console.error(`  ${f}\n`);
    process.exit(1);
  }
  console.log(
    `check-biome-sky: ${counted.length}/${BIOME_SKY_CEILING} interior(s) ` +
      `still take their construction from their biome (of ${rows} ` +
      `atmospheric row(s)); every other place says what it is made of, or ` +
      `is open to the sky.`,
  );
  void relative;
  void REPO;
}

function main(): void {
  if (process.argv.includes("--report")) return report();
  lint();
}

if (process.argv[1] && /check-biome-sky\.ts$/.test(process.argv[1])) main();

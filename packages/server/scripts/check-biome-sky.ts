/**
 * check-biome-sky — ⭐⭐ **which interiors still take what is over them
 * from their biome, and can that list only get shorter?**
 *
 * ## Why
 *
 * Until the rubber build, whether a place was under the sky was one bit
 * on its biome (`SkyExposedBiome`). It is a fact about CONSTRUCTION, so a
 * place now says it: `enclosure:` (the walls) and `roof:`, each a layer,
 * a list of layers, or `none` (`lib/spatial/Enclosed.ts`).
 *
 * ⭐ **The default is OPEN.** Open sky is the absence of construction, so
 * the eventual default for a place that authors nothing is no walls and
 * no roof — and streets, yards and fields are right with no edit, ever.
 * **Outdoor rows are never debt.** The debt is the INTERIORS: places
 * whose biome is not sky-exposed and that have not yet said what they are
 * made of, which still read the legacy answer (their walls' material on
 * five faces). Each one is a line in {@link INTERIORS_FROM_THE_BIOME}.
 *
 * ⚠ BOTH keys, because at zero BOTH defaults flip to `none`: an interior
 * that authored only its roof would lose its walls.
 *
 * ## What is never counted
 *
 *  - a row whose CLASS declares its roof (a `roofDefaults()` override
 *    anywhere in its ancestry — a vessel, a hive, a cold store, a cellar
 *    cut into rock): it is never undeclared;
 *  - a row under a sky biome (it is open, which is the default);
 *  - an `Offstage` row (a parking room is not a place: no volume, no air).
 *
 * ⚠ A row with NO `_biomePath` IS counted: the runtime walk answers *not
 * sky-exposed* for it, so it reads the legacy interior answer today —
 * including a few the fiction calls outdoor (the crossroads' meadows).
 * Paying those is a sky `_biomePath`, or `enclosure: none` + `roof: none`.
 *
 * ## The clauses
 *
 *   (a) every counted interior is listed; the list may fall and may never
 *       rise — a new interior must say what it is made of from birth;
 *   (b) a listed row that has since authored both keys (or now reads
 *       open) is STALE and fails: paying the debt deletes the line.
 *
 * ⭐ At zero: `Location`'s two defaults answer `none`, the legacy branch
 * of `AtmosphericMixin.construction()` is deleted, and `SkyExposedBiome`
 * retires (biome-normalization-slate).
 *
 * ## Usage
 *
 *   pnpm lint:biome-sky            # the gate
 *   pnpm lint:biome-sky --report   # print today's census, for the list
 */

